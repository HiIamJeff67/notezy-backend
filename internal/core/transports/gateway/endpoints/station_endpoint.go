	RestoreMyStationsByIds(ctx *gin.Context)
	DeleteMyStationById(ctx *gin.Context)
	DeleteMyStationsByIds(ctx *gin.Context)
	HardDeleteMyStationById(ctx *gin.Context)
	HardDeleteMyStationsByIds(ctx *gin.Context)
