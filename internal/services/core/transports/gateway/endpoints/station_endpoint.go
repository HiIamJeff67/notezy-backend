	DeleteMyStationPermission(ctx *gin.Context)
	DeleteMyStationPermissions(ctx *gin.Context)
	LeaveMyStation(ctx *gin.Context)
	LeaveMyStations(ctx *gin.Context)

	/* ============================== GraphQL Methods ============================== */
